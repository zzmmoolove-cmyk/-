const stemRow = (stem: string, wx: string, image: string, note: string): Concept => {
  const row = MUTAGEN_TABLE[stem];
  const hua = row ? ['禄', '权', '科', '忌'].map((m, i) => `${row[i]}化${m}`).join('、') : '';
  return {
    name: stem,
    kind: '天干',
    brief: `${wx}：${image}。`,
    detail: `${wx}。${note}宫干为「${stem}」，代表这一宫自己的气；宫干引动本宫星曜即「自化」，引动他宫星曜即「飞化」。`,
    extra: hua ? [{ label: `${stem}干四化`, value: hua }] : undefined,
    tags: [wx, '宫干'],
  };
};

