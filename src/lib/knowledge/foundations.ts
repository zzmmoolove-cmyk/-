/** 地支的场地性质（完整句），用于弹窗 */
export function branchFeature(branch: string): string {
  return BRANCHES[branch]?.tags?.find((t) => t.startsWith('四')) ?? '';
}

/** 地支的场地性质（四正/四墓/四马），用于批注 */
export function branchShort(branch: string): string {
  const t = branchFeature(branch);
  return t.slice(0, 2);
}

export function branchElement(branch: string): string {
  return BRANCHES[branch]?.tags?.[0] ?? '';
}

export function stemElement(stem: string): string {
  return STEMS[stem]?.tags?.[0] ?? '';
}
