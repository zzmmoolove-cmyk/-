/** 按省份 + 关键字搜索城市；关键字同时匹配城市名与省份名 */
export function searchCities(query: string, province?: string, limit = 60): City[] {
  const q = query.trim().replace(/[市地区盟自治州]$/g, '').trim();
  return CITIES.filter((c) => {
    if (province && c.province !== province) return false;
    if (!q) return true;
    return c.name.includes(q) || c.province.includes(q);
  }).slice(0, limit);
}

export function findCity(name: string, province?: string): City | undefined {
  return CITIES.find((c) => c.name === name && (!province || c.province === province));
}

/** 由经度反查最近的城市（用于回填已有命盘） */
export function nearestCity(longitude: number): City {
  return CITIES.reduce((best, c) =>
    Math.abs(c.longitude - longitude) < Math.abs(best.longitude - longitude) ? c : best,
  CITIES[0]);
}

